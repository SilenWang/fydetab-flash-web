#!/usr/bin/env node
// Build the sample pair the zip path is demonstrated with:
//
//   web/samples/demo-update.img   the synthetic RKFW image (Go's DemoImage)
//   web/samples/demo-update.zip   the same bytes deflated inside a ZIP64
//                                 package, with decoys in front of it — the
//                                 shape of an official firmware download
//
// Both are generated, never committed: `pixi run sample` regenerates them and
// .gitignore keeps them out of the tree.
//
// Usage: node tools/make-sample.mjs [--dir web/samples]

import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { DEFLATE, STORE, writeZip } from './zip-writer.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dirIndex = process.argv.indexOf('--dir');
const outDir = resolve(root, dirIndex > 0 ? process.argv[dirIndex + 1] : join('web', 'samples'));

mkdirSync(outDir, { recursive: true });

const imgPath = join(outDir, 'demo-update.img');
const zipPath = join(outDir, 'demo-update.zip');

execFileSync('go', ['run', './tools/demo-image', '--out', imgPath], { cwd: root, stdio: 'inherit' });
const image = new Uint8Array(readFileSync(imgPath));

// A package shaped like a vendor download: documentation and a loader next to
// the image, and a ZIP64 central directory so that path is exercised too.
const readme = new TextEncoder().encode(
  'Synthetic demo package generated by tools/make-sample.mjs — not a Rockchip release.\n',
);
const loader = new Uint8Array(1024);
for (let i = 0; i < loader.length; i += 1) loader[i] = (i * 31) & 0xff;

const zip = writeZip(
  [
    { name: 'README.txt', data: readme, method: STORE },
    { name: 'MiniLoaderAll.bin', data: loader, method: DEFLATE },
    { name: 'Image/update.img', data: image, method: DEFLATE },
  ],
  { forceZip64: true, comment: 'fydetab-flash-web demo package' },
);
writeFileSync(zipPath, zip);

const mib = (n) => `${(n / 1024 / 1024).toFixed(2)} MiB`;
console.log(`demo-update.img: ${image.length} B`);
console.log(`demo-update.zip: ${zip.length} B (ZIP64, deflate, ${statSync(zipPath).size} on disk)`);
console.log(`  image inside: ${mib(image.length)} → package ${mib(zip.length)}`);
console.log(`  served at /samples/demo-update.img and /samples/demo-update.zip under pixi run dev`);
