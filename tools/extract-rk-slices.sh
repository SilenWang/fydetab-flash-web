#!/usr/bin/env bash
#
# Extract the small slices of an RKFW update image that the offline parser
# tests replay, plus a manifest that internal/testimage reads.
#
# The RKFW/RKAF payloads are multi-GiB; the slices are a few KiB. They are
# enough to check the header fields, the item table, the parameter partition,
# the RKAF CRC trailer and the trailing MD5 without moving the image around.
#
# Correctness notes (learned the hard way, see docs/rkfw-rkaf-format.md §3):
#   * item name/path fields are NOT zero-filled: heap garbage follows the first
#     NUL, so every string is cut at the first NUL (`cstr` below).  Stripping
#     NULs instead of cutting corrupts names such as "parameter" and silently
#     defeats the search for the parameter item.
#   * the item field at +104 counts 2 KiB blocks, not bytes; the payload length
#     is at +108.  Slicing with +104 produces a 1-byte "parameter".
#
# Read-only: this script never writes to a device and never modifies the image.
#
# usage: tools/extract-rk-slices.sh <update.img> [outdir]
#
# Output: <outdir>/{rkfw-head,rkaf-head,parameter,rkaf-crc-trailer,md5-tail}.bin
#         <outdir>/manifest.txt  (read by `RKFW_SLICES_DIR=... pixi run test`)

set -euo pipefail

IMG=${1:?usage: $0 <update.img> [outdir]}
OUT=${2:-rk-slices}

for tool in dd od tr sed stat sha256sum; do
	command -v "$tool" >/dev/null 2>&1 || {
		echo "missing required tool: $tool" >&2
		exit 1
	}
done

[ -f "$IMG" ] || {
	echo "no such file: $IMG" >&2
	exit 1
}

magic=$(dd if="$IMG" bs=1 count=4 status=none)
case "$magic" in
PK*)
	echo "$IMG looks like a zip; unzip it first (this script needs random access to the .img)" >&2
	exit 1
	;;
RKFW) ;;
*)
	echo "not an RKFW container (magic: $(printf '%s' "$magic" | od -An -c | tr -s ' '))" >&2
	exit 1
	;;
esac

mkdir -p "$OUT"

SIZE=$(stat -c %s "$IMG")
SHA256=$(sha256sum "$IMG" | cut -d' ' -f1)

u16() { od -An -tu2 -j "$1" -N2 "$IMG" | tr -d ' \n'; }
u32() { od -An -tu4 -j "$1" -N4 "$IMG" | tr -d ' \n'; }
slice() { dd if="$IMG" of="$2" bs=1M iflag=skip_bytes,count_bytes skip="$1" count="$3" status=none; }

# cstr <offset> <maxlen>: the string up to (excluding) the first NUL byte.
cstr() {
	local hex first
	hex=$(dd if="$IMG" bs=1 skip="$1" count="$2" status=none | od -An -tx1 | tr -d ' \n')
	first=${hex%%00*}
	[ -n "$first" ] || return 0
	printf '%b' "$(printf '%s' "$first" | sed 's/../\\x&/g')"
}

HEAD_LEN=$(u16 4)
CHIP=$(u32 21)
LOADER_OFF=$(u32 25)
LOADER_LEN=$(u32 29)
IMAGE_OFF=$(u32 33)
IMAGE_LEN=$(u32 37)

[ "$HEAD_LEN" -ge 102 ] || {
	echo "head_len $HEAD_LEN is smaller than the 102-byte header; stop" >&2
	exit 1
}

RKAF_LENGTH=$(u32 $((IMAGE_OFF + 4)))
NPARTS=$(u32 $((IMAGE_OFF + 136)))

echo "image          $IMG"
echo "size           $SIZE bytes"
echo "sha256         $SHA256"
printf 'head_len       %s\n' "$HEAD_LEN"
printf 'chip           0x%08x\n' "$CHIP"
printf 'loader         offset %s length %s\n' "$LOADER_OFF" "$LOADER_LEN"
printf 'image_offset   %s\n' "$IMAGE_OFF"
printf 'image_length   %s\n' "$IMAGE_LEN"
printf 'rkaf.length    %s\n' "$RKAF_LENGTH"
printf 'rkaf.num_parts %s\n' "$NPARTS"

PARAM_POS=""
PARAM_SIZE=""
echo
printf '%-14s %12s %12s %10s %14s\n' name pos nand_addr +104 size
i=0
while [ "$i" -lt "$NPARTS" ]; do
	base=$((IMAGE_OFF + 140 + i * 112))
	name=$(cstr "$base" 32)
	pos=$(u32 $((base + 96)))
	addr=$(u32 $((base + 100)))
	blocks=$(u32 $((base + 104)))
	size=$(u32 $((base + 108)))
	printf '%-14s %12s %12s %10s %14s\n' "$name" "$pos" "$addr" "$blocks" "$size"
	if [ "$name" = "parameter" ]; then
		PARAM_POS=$pos
		PARAM_SIZE=$size
	fi
	i=$((i + 1))
done

echo
slice 0 "$OUT/rkfw-head.bin" "$HEAD_LEN"
slice "$IMAGE_OFF" "$OUT/rkaf-head.bin" 2048

if [ -n "$PARAM_POS" ]; then
	slice $((IMAGE_OFF + PARAM_POS)) "$OUT/parameter.bin" "$PARAM_SIZE"
	echo "parameter item: $PARAM_SIZE bytes at image offset $((IMAGE_OFF + PARAM_POS))"
else
	echo "warning: no item named 'parameter' in the table" >&2
fi

slice $((IMAGE_OFF + RKAF_LENGTH)) "$OUT/rkaf-crc-trailer.bin" 4

# The MD5 tail is either right after the archive (signed images) or at EOF-32.
# Pick by content: exactly 32 ASCII hex digits.  Arithmetic alone misfires on
# images that carry padding after the archive.  The probe goes through a file so
# a matching grep cannot SIGPIPE the dd and turn a match into a miss.
PROBE="$OUT/.tail-probe"
slice $((IMAGE_OFF + RKAF_LENGTH + 4)) "$PROBE" 32
if LC_ALL=C grep -Eq '^[0-9a-fA-F]{32}$' "$PROBE"; then
	MD5_OFF=$((IMAGE_OFF + RKAF_LENGTH + 4))
	MD5_WHERE="after the archive (signed image)"
else
	MD5_OFF=$((SIZE - 32))
	MD5_WHERE="EOF-32"
fi
rm -f "$PROBE"
slice "$MD5_OFF" "$OUT/md5-tail.bin" 32

{
	echo "# generated by tools/extract-rk-slices.sh"
	echo "image=$IMG"
	echo "size=$SIZE"
	echo "sha256=$SHA256"
	echo "image_offset=$IMAGE_OFF"
	echo "rkaf_length=$RKAF_LENGTH"
	echo "md5_offset=$MD5_OFF"
	echo "slice=rkfw-head 0 $HEAD_LEN rkfw-head.bin"
	echo "slice=rkaf-head $IMAGE_OFF 2048 rkaf-head.bin"
	if [ -n "$PARAM_POS" ]; then
		echo "slice=parameter $((IMAGE_OFF + PARAM_POS)) $PARAM_SIZE parameter.bin"
	fi
	echo "slice=rkaf-crc-trailer $((IMAGE_OFF + RKAF_LENGTH)) 4 rkaf-crc-trailer.bin"
	echo "slice=md5-tail $MD5_OFF 32 md5-tail.bin"
} >"$OUT/manifest.txt"

echo
echo "md5 tail at $MD5_OFF ($MD5_WHERE): $(cat "$OUT/md5-tail.bin")"
echo "rkaf-crc-trailer: $(od -An -tx1 "$OUT/rkaf-crc-trailer.bin" | tr -d ' \n')"
echo
echo "wrote:"
ls -l "$OUT"
echo
echo "Attach the .bin files and manifest.txt to the issue, or run:"
echo "  RKFW_SLICES_DIR=$OUT pixi run test"
