package gpt

// Serialization of a planned GPT.
//
// The firmware image does not carry GPT bytes: the host derives them from the
// parameter table and writes them over the first and last sectors of the
// device. This file produces exactly those bytes, so the same layout the
// planner validated can be written and then read back byte for byte.
//
// Geometry written by Encode:
//
//	LBA 0          protective MBR (one 0xEE partition covering the disk)
//	LBA 1          primary header
//	LBA 2..33      primary entry array
//	LBA N-33..N-2  backup entry array (same entries)
//	LBA N-1        backup header
//
// All multi-byte fields are little-endian, as the UEFI specification requires.

import (
	"crypto/sha256"
	"encoding/binary"
	"fmt"
	"hash/crc32"
	"strings"
	"unicode/utf16"
)

const (
	// PrimarySectors is the whole primary GPT region: protective MBR, header
	// and entry array.
	PrimarySectors = 1 + 1 + EntriesSectors // 34
	// BackupSectors is the backup entry array plus the backup header.
	BackupSectors = EntriesSectors + 1 // 33
	// HeaderSize is sizeof(EFI_PARTITION_TABLE_HEADER).
	HeaderSize = 92
	// NameChars is how many UTF-16 code units a partition entry name holds.
	NameChars = 36
	// PMBREntryOffset is where the legacy MBR partition record 1 starts.
	PMBREntryOffset = 446
	// PMBRTypeGPT marks the single protective MBR partition.
	PMBRTypeGPT = 0xEE
	// AttributeBootable is the GPT "legacy BIOS bootable" attribute bit.
	AttributeBootable uint64 = 1 << 2

	// mbrSignature is the 0xAA55 boot signature, little-endian.
	mbrSignature = 0xAA55
	// headerSignature is "EFI PART" read as a little-endian uint64.
	headerSignature = 0x5452415020494645
	// headerRevision is GPT revision 1.0.
	headerRevision = 0x00010000
)

// EncodeOptions tunes the serialization. It exists so the generated bytes can
// be reproducible.
type EncodeOptions struct {
	// Seed makes the disk and partition GUIDs deterministic: the same seed and
	// layout always produce the same bytes, so a retried write is identical to
	// the first attempt (which the read-back comparison can then rely on).
	// A seed of "" still produces deterministic GUIDs derived from the layout.
	Seed string
}

// Image is the serialized form of a layout: the two byte ranges a writer has
// to transfer.
type Image struct {
	// PrimaryLBA is 0; Primary holds PrimarySectors sectors.
	PrimaryLBA uint64
	Primary    []byte
	// BackupLBA is the first sector of the backup entry array (N-33); Backup
	// holds BackupSectors sectors, ending with the backup header at N-1.
	BackupLBA uint64
	Backup    []byte
}

// Sectors returns the sector count of the primary and the backup region.
func (img *Image) Sectors() (primary, backup uint64) {
	return uint64(len(img.Primary)) / 512, uint64(len(img.Backup)) / 512
}

// Encode renders the layout as the two GPT regions. It refuses a layout whose
// disk size is unknown: the backup entries and header live at the end of the
// disk, so a guessed size would put them where the device does not read them.
func Encode(lay *Layout, opts EncodeOptions) (*Image, error) {
	if lay == nil {
		return nil, fmt.Errorf("gpt: nil layout")
	}
	if !lay.DiskKnown || lay.DiskSectors < uint64(FirstUsableLBA)*2 {
		return nil, fmt.Errorf("gpt: the disk size is unknown (%d sectors); cannot place the backup GPT", lay.DiskSectors)
	}
	if len(lay.Entries) > EntryCount {
		return nil, fmt.Errorf("gpt: %d entries exceed the %d slots", len(lay.Entries), EntryCount)
	}

	primary := make([]byte, PrimarySectors*512)
	backup := make([]byte, BackupSectors*512)

	// 1. Protective MBR: a single partition of type 0xEE that spans the disk.
	putMBR(primary[:512], lay.DiskSectors)

	// 2. Entry array.
	entries := primary[2*512:]
	for i := range lay.Entries {
		if err := putEntry(entries[i*EntrySize:], lay.Entries[i], lay, opts); err != nil {
			return nil, err
		}
	}
	entriesCRC := crc32.ChecksumIEEE(entries[:EntryCount*EntrySize])

	// 3. Primary header.
	hdr := primary[512:1024]
	putHeader(hdr, headerFields{
		myLBA:        PrimaryHeaderLBA,
		alternateLBA: lay.DiskSectors - 1,
		firstUsable:  lay.FirstUsableLBA,
		lastUsable:   lay.LastUsableLBA,
		entryLBA:     PrimaryEntriesLBA,
		entriesCRC:   entriesCRC,
		diskGUID:     guidFor(opts.Seed, "disk", ""),
	})

	// 4. Backup: same entries, then a header that points at itself and at the
	//    primary.
	copy(backup[:EntriesSectors*512], entries[:EntryCount*EntrySize])
	putHeader(backup[EntriesSectors*512:], headerFields{
		myLBA:        lay.DiskSectors - 1,
		alternateLBA: PrimaryHeaderLBA,
		firstUsable:  lay.FirstUsableLBA,
		lastUsable:   lay.LastUsableLBA,
		// The backup entry array immediately follows the last usable LBA.
		entryLBA:   lay.LastUsableLBA + 1,
		entriesCRC: entriesCRC,
		diskGUID:   guidFor(opts.Seed, "disk", ""),
	})

	return &Image{
		PrimaryLBA: 0,
		Primary:    primary,
		BackupLBA:  lay.BackupEntriesLBA,
		Backup:     backup,
	}, nil
}

func putMBR(b []byte, diskSectors uint64) {
	// CHS fields stay zero: the entry is addressed by LBA, and a sector count
	// of 0xFFFFFFFF is the conventional "whole disk" marker.
	p := b[PMBREntryOffset:]
	p[0] = 0x00 // not bootable
	p[4] = PMBRTypeGPT
	binary.LittleEndian.PutUint32(p[8:12], 1)
	binary.LittleEndian.PutUint32(p[12:16], 0xFFFFFFFF)
	if diskSectors < 0xFFFFFFFF {
		binary.LittleEndian.PutUint32(p[12:16], uint32(diskSectors-1))
	}
	binary.LittleEndian.PutUint16(b[510:512], mbrSignature)
}

type headerFields struct {
	myLBA        uint64
	alternateLBA uint64
	firstUsable  uint64
	lastUsable   uint64
	entryLBA     uint64
	entriesCRC   uint32
	diskGUID     [16]byte
}

func putHeader(b []byte, f headerFields) {
	for i := range b {
		b[i] = 0
	}
	binary.LittleEndian.PutUint64(b[0:8], headerSignature)
	binary.LittleEndian.PutUint32(b[8:12], headerRevision)
	binary.LittleEndian.PutUint32(b[12:16], HeaderSize)
	// b[16:20] header CRC is filled in last.
	binary.LittleEndian.PutUint64(b[24:32], f.myLBA)
	binary.LittleEndian.PutUint64(b[32:40], f.alternateLBA)
	binary.LittleEndian.PutUint64(b[40:48], f.firstUsable)
	binary.LittleEndian.PutUint64(b[48:56], f.lastUsable)
	copy(b[56:72], f.diskGUID[:])
	binary.LittleEndian.PutUint64(b[72:80], f.entryLBA)
	binary.LittleEndian.PutUint32(b[80:84], EntryCount)
	binary.LittleEndian.PutUint32(b[84:88], EntrySize)
	binary.LittleEndian.PutUint32(b[88:92], f.entriesCRC)
	binary.LittleEndian.PutUint32(b[16:20], crc32.ChecksumIEEE(b[:HeaderSize]))
}

func putEntry(b []byte, e Entry, lay *Layout, opts EncodeOptions) error {
	if e.Sectors == 0 {
		return fmt.Errorf("gpt: entry %q has no size", e.Name)
	}
	for i := range b[:EntrySize] {
		b[i] = 0
	}
	typeGUID := guidFor(opts.Seed, "type", e.Name)
	uniqueGUID := guidFor(opts.Seed, "part", fmt.Sprintf("%d/%s", e.Index, e.Name))
	copy(b[0:16], typeGUID[:])
	copy(b[16:32], uniqueGUID[:])
	binary.LittleEndian.PutUint64(b[32:40], e.FirstLBA)
	binary.LittleEndian.PutUint64(b[40:48], e.LastLBA)
	var attrs uint64
	if hasFlag(e.Flags, "bootable") {
		attrs |= AttributeBootable
	}
	binary.LittleEndian.PutUint64(b[48:56], attrs)
	writeName(b[56:128], e.Name)
	return nil
}

// writeName stores the partition name as UTF-16LE in the fixed-size field.
func writeName(dst []byte, name string) {
	units := utf16.Encode([]rune(name))
	if len(units) > NameChars {
		units = units[:NameChars]
	}
	for i, u := range units {
		binary.LittleEndian.PutUint16(dst[i*2:], u)
	}
}

func hasFlag(flags []string, want string) bool {
	for _, f := range flags {
		if strings.EqualFold(f, want) {
			return true
		}
	}
	return false
}

// guidFor derives a stable GUID from the seed and its role. The vendor tool
// randomises these values and nothing on the device reads them back, so a
// deterministic derivation only buys reproducibility (identical bytes on a
// retried write); it keeps the RFC 4122 shape so the field looks like a UUID.
func guidFor(seed, role, name string) [16]byte {
	h := sha256.Sum256([]byte("gpt\x00" + seed + "\x00" + role + "\x00" + name))
	var g [16]byte
	copy(g[:], h[:16])
	g[6] = (g[6] & 0x0F) | 0x40 // version 4
	g[8] = (g[8] & 0x3F) | 0x80 // RFC 4122 variant
	return g
}
