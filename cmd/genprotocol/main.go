// Command genprotocol renders web/probe/protocol.js from the Go protocol
// package, so the browser never carries a hand-copied command table.
//
// Usage:
//
//	go run ./cmd/genprotocol            # write web/probe/protocol.js
//	go run ./cmd/genprotocol -check     # fail if the committed file is stale
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/SilenWang/rk3588-webflasher/internal/rockusb"
)

func main() {
	out := flag.String("out", filepath.Join("web", "probe", "protocol.js"), "output path")
	check := flag.Bool("check", false, "verify the file is up to date instead of writing it")
	flag.Parse()

	want, err := render()
	if err != nil {
		fmt.Fprintf(os.Stderr, "genprotocol: %v\n", err)
		os.Exit(1)
	}

	got, err := os.ReadFile(*out)
	if err != nil && !os.IsNotExist(err) {
		fmt.Fprintf(os.Stderr, "genprotocol: %v\n", err)
		os.Exit(1)
	}

	if *check {
		if !bytes.Equal(got, want) {
			fmt.Fprintf(os.Stderr, "genprotocol: %s is stale; run `pixi run gen`\n", *out)
			os.Exit(1)
		}
		fmt.Printf("genprotocol: %s is up to date\n", *out)
		return
	}

	if bytes.Equal(got, want) {
		fmt.Printf("genprotocol: %s unchanged\n", *out)
		return
	}
	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "genprotocol: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, want, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "genprotocol: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("genprotocol: wrote %s\n", *out)
}

func render() ([]byte, error) {
	var b strings.Builder

	b.WriteString(`// Code generated by cmd/genprotocol from internal/rockusb; DO NOT EDIT.
//
// Source of truth: internal/rockusb/protocol.go, itself transcribed from
// Rockchip's GPL-2.0 rkdeveloptool (RKComm.h / RKComm.cpp / RKDevice.h).
// Regenerate with ` + "`pixi run gen`" + `.

export const PROTOCOL = "rockusb/M0-readonly";
export const READ_ONLY = true;

export const CBW_SIGNATURE = 0x43425355; // "USBC"
export const CSW_SIGNATURE = 0x53425355; // "USBS"
export const CBW_LENGTH = 31;
export const CSW_LENGTH = 13;
export const DIRECTION_IN = 0x80;
export const DIRECTION_OUT = 0x00;
export const ROCKCHIP_VENDOR_ID = 0x2207;
export const STATUS_PASSED = 0x00;
export const STATUS_FAILED = 0x01;

`)

	b.WriteString("export const ERROR_NAMES = {\n")
	codes := []rockusb.ErrorCode{
		rockusb.ErrSuccess,
		rockusb.ErrDeviceOpenFailed,
		rockusb.ErrDeviceWriteFailed,
		rockusb.ErrDeviceReadFailed,
		rockusb.ErrCmdNotMatch,
		rockusb.ErrDeviceUnready,
		rockusb.ErrFailed,
		rockusb.ErrDeviceNotSupport,
		rockusb.ErrRequestFail,
	}
	for _, code := range codes {
		// Negative numbers are not valid bare object keys in JavaScript.
		fmt.Fprintf(&b, "  %s: %s,\n", strconv.Quote(strconv.Itoa(int(code))), strconv.Quote(code.String()))
	}
	b.WriteString("};\n\n")

	b.WriteString(`/**
 * The complete set of commands the probe may issue. Any opcode outside this
 * table is rejected before a transfer is attempted.
 */
export const COMMANDS = [
`)
	for _, c := range rockusb.Commands {
		fmt.Fprintf(&b, "  { op: 0x%02X, name: %s, transferLength: %d, dataLength: %d, allowShort: %t, description: %s },\n",
			byte(c.Op), strconv.Quote(c.Name), c.TransferLength, c.DataLength, c.AllowShort, strconv.Quote(c.Description))
	}
	b.WriteString("];\n\n")

	b.WriteString("export const COMMANDS_BY_OP = Object.freeze(\n  Object.fromEntries(COMMANDS.map((c) => [c.op, c])),\n);\n\n")

	b.WriteString("export const STORAGE_NAMES = Object.freeze({\n")
	ids := make([]int, 0, 4)
	for id := range storageNames() {
		ids = append(ids, id)
	}
	sort.Ints(ids)
	for _, id := range ids {
		fmt.Fprintf(&b, "  %d: %s,\n", id, strconv.Quote(rockusb.StorageName(id)))
	}
	b.WriteString("});\n\n")

	b.WriteString("export const MANUFACTURER_NAMES = Object.freeze([\n")
	for _, name := range manufacturerNames() {
		fmt.Fprintf(&b, "  %s,\n", strconv.Quote(name))
	}
	b.WriteString("]);\n")

	return []byte(b.String()), nil
}

// storageNames is intentionally re-derived through the public API: genprotocol
// only needs the ids, never the internal map.
func storageNames() map[int]string {
	return map[int]string{1: rockusb.StorageName(1), 2: rockusb.StorageName(2), 3: rockusb.StorageName(3), 9: rockusb.StorageName(9)}
}

func manufacturerNames() []string {
	return []string{"SAMSUNG", "TOSHIBA", "HYNIX", "INFINEON", "MICRON", "RENESAS", "ST", "INTEL"}
}
